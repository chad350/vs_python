rows = [
    {"주문번호": "O-101", "결제금액": "12,000"},
    {"주문번호": "O-102", "결제금액": "3,500"},
]

# {'O-101': '12,000', 'O-102': '3,500'}  <-  문자로 우선
# {'O-101': 12000, 'O-102': 3500}  <-  숫자는 시간 되는대로
orders = { r["주문번호"] : int(r["결제금액"].replace(",", ""))  for r in rows }
print(orders)